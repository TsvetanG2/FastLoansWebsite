// Renders the approved logo mark (public/logo-mark.svg, unchanged) to a PNG for the emails and
// writes it as base64 into src/lib/email-logo.ts. Email clients do not show SVG, and the image is
// embedded in the message (CID attachment) instead of loaded from a server — no remote images,
// no tracking. Run again only if the logo changes: node scripts/make-email-logo.mjs
import fs from 'node:fs';
import sharp from 'sharp';

const HEIGHT = 112; // 2x the 56px it is shown at, so it stays sharp on retina screens
const png = await sharp('public/logo-mark.svg', { density: 600 })
  .resize({ height: HEIGHT })
  .png({ compressionLevel: 9 })
  .toBuffer();
const { width, height } = await sharp(png).metadata();

fs.writeFileSync(
  'src/lib/email-logo.ts',
  `// Generated by scripts/make-email-logo.mjs from public/logo-mark.svg — do not edit.
export const EMAIL_LOGO = {
  contentId: 'rf-logo',
  filename: 'royal-finance.png',
  width: ${Math.round(width / 2)},
  height: ${Math.round(height / 2)},
  base64: '${png.toString('base64')}',
};
`,
);
console.log(`email logo: ${width}x${height}px, ${png.length} bytes`);
